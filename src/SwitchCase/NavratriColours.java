package SwitchCase;
public class NavratriColours {
    public static void main(String[] args) {
        int day = 1;
        switch (day) {
            case 1:
                System.out.println("Day 1 - Yellow");
                break;
            case 2:
                System.out.println("Day 2 - Green");
                break;
            case 3:
                System.out.println("Day 3 - Grey");
                break;
            case 4:
                System.out.println("Day 4 - Orange");
                break;
            case 5:
                System.out.println("Day 5 - White");
                break;
            case 6:
                System.out.println("Day 6 - Red");
                break;
            case 7:
                System.out.println("Day 7 - Royal Blue");
                break;
            case 8:
                System.out.println("Day 8 - purple");
                break;
            case 9:
                System.out.println("Day 9 - Pink");
                break;
            default:
                System.out.println("Invalid Day");
        }
    }
}





