package JavaBasicProgrammingElements.Lab;

public class OperatorsEx1 {
    public class OperatorsDemo {
        public static void main(String[] args){

            // Pre-increment
            int a = 3;
            int b = ++a;
            System.out.println(a);
            System.out.println(b);

            // Post-increment
            b = a++;
            System.out.println(b);

            // Pre-decrement
            b = --a;
            System.out.println(b);

        }
    }
}
