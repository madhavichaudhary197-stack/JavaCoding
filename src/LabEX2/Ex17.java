package LabEX2;

public class Ex17 {
    public class ReverseNumberPattern{
        public static void main(String[] args){
            for (int i = 1; i <= 5; i ++) {
                for (int j = i; j >= 1; j--) {
                    System.out.println(j + " ");
                }
            System.out.println();
            }
        }
    }
}
