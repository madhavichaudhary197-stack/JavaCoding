package LabEX2;

public class Ex20 {
    public class StarPattern{
        public static void main(String[] args){

            for (int i = 1; i <= 5; i++){
                for (int j = 1; j <= i; j++){
                    System.out.println(" * ");
                }
                System.out.println();
            }
        }
    }
}
