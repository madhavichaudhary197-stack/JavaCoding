package LabEX2;

public class Ex14 {
    public class SquersAndCubes {
        public static void main(String[] args){
            System.out.println("Numbers/tSqures/tCube");
            for (int i = 1; i <= 10; i ++) {
                int square = i * i ;
                int cube = i * i * i;
                System.out.println(i + "\t" + square + "\t" + cube);

            }
        }
    }
}
