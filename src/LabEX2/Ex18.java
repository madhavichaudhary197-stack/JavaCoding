package LabEX2;

public class Ex18 {
    public class DesendingNumberPattern{
        public static void main(String[] args){

            for (int i = 6; i >= 1; i--) {
                for (int j = 1; j >= 1; j--){
                    System.out.println(j + " ");
                }
                System.out.println();
            }
        }
    }
}
